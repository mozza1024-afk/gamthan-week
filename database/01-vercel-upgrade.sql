-- 5) 담당자가 수시로 입력하는 배포/제출 기록
create table if not exists public.offline_distribution_entries (
  id uuid primary key default gen_random_uuid(),
  site_id uuid not null references public.offline_sites(id) on delete restrict,
  organization_id text not null,
  entry_date date not null default current_date,
  distributed_qty integer not null default 0 check (distributed_qty >= 0),
  submitted_qty integer not null default 0 check (submitted_qty >= 0),
  note text,
  entered_by_admin_id text not null,
  created_at timestamptz not null default now()
);
create index if not exists offline_entries_site_date_idx on public.offline_distribution_entries (site_id, entry_date desc);
create index if not exists offline_entries_org_idx on public.offline_distribution_entries (organization_id);

-- 6) 관리자 열람/변경 기록
create table if not exists public.admin_access_logs (
  id bigint generated by default as identity primary key,
  admin_user_id text not null,
  admin_role text,
  organization_id text,
  action text not null,
  target_type text,
  target_id text,
  detail jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists admin_access_logs_created_idx on public.admin_access_logs (created_at desc);
create index if not exists admin_access_logs_admin_idx on public.admin_access_logs (admin_user_id);

-- 브라우저가 DB를 직접 읽지 못하게 유지합니다. Vercel 서버 API만 Secret Key로 접근합니다.
alter table public.admin_users enable row level security;
alter table public.offline_sites enable row level security;
alter table public.offline_distribution_entries enable row level security;
alter table public.admin_access_logs enable row level security;

commit;

