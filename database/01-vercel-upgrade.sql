-- 감탄위크 Vercel + Supabase 운영구조 업그레이드
-- 1회 실행: 생년월일 로그인, 관리자 역할 분리, 오프라인 300부/6개 지점 관리

begin;

-- 1) 참여자 로그인: 생년월일 6자리는 원문을 저장하지 않고 해시/솔트만 저장합니다.
alter table public.participants add column if not exists birth_hash text;
alter table public.participants add column if not exists birth_salt text;

-- 2) 운영 설정: 오프라인 일기장 총수량
insert into public.app_settings (setting_key, setting_value)
values ('OFFLINE_DIARY_TOTAL', '300')
on conflict (setting_key) do update
set setting_value = excluded.setting_value,
    updated_at = now();

-- 3) 관리자 계정
create table if not exists public.admin_users (
  id uuid primary key default gen_random_uuid(),
  email text not null unique,
  display_name text not null,
  password_hash text not null,
  password_salt text not null,
  role text not null check (role in ('super_admin','org_admin')),
  organization_id text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists admin_users_org_idx on public.admin_users (organization_id);

-- 4) 오프라인 일기장 배포지점 6곳
create table if not exists public.offline_sites (
  id uuid primary key default gen_random_uuid(),
  organization_id text not null,
  organization_name text not null,
  site_name text not null unique,
  address text,
  opening_hours text,
  allocated_quantity integer not null default 0 check (allocated_quantity >= 0),
  is_active boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- 기관 테이블에 같은 이름이 있으면 그 id를 사용하고, 없으면 오프라인 전용 식별자를 사용합니다.
